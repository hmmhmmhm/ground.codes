const foldLatin = (value) =>
  String(value)
    .replace(/[Ɔɔ]/g, "o")
    .replace(/[Ɛɛ]/g, "e")
    .replace(/[Ʋʋ]/g, "v")
    .replace(/[Ƒƒ]/g, "f")
    .replace(/[Ŋŋ]/g, "ng")
    .replace(/[Ɲɲ]/g, "ny")
    .replace(/[Ɣɣ]/g, "gh")
    .replace(/[Ɗɗ]/g, "d")
    .replace(/[Ɓɓ]/g, "b")
    .replace(/[Ƴƴ]/g, "y")
    .normalize("NFD")
    .replace(/\p{Mark}/gu, "")
    .replace(/[’'`´/#?\-]/g, "")
    .replace(/\s+/g, " ")
    .trim();

const titleAscii = (value) => {
  const compact = foldLatin(value)
    .replace(/[^A-Za-z]/g, "")
    .toLowerCase();
  if (!compact) return "";
  return `${compact[0].toUpperCase()}${compact.slice(1)}`;
};

