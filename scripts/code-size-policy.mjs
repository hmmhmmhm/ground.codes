export const MAX_SOURCE_LINES = 450;

export const GENERATED_SOURCE_FILES = new Map([
  [
    "apps/web/lib/map/planetary-landmark-labels.ts",
    "scripts/generate-planetary-landmark-labels.mjs",
  ],
]);

const countLines = (source) => source.split(/\r?\n/).length;

export const isCheckedSourcePath = (path) =>
  !path.endsWith(".d.ts") && /\.(?:ts|tsx|mjs)$/.test(path);

export const evaluateSourceFile = ({
  path,
  source,
  generatedFiles = GENERATED_SOURCE_FILES,
}) => {
  const lines = countLines(source);
  if (lines <= MAX_SOURCE_LINES) return null;

  const generator = generatedFiles.get(path);
  const generatedHeader = generator ? `// Generated by ${generator}.` : null;
  if (generatedHeader && source.startsWith(generatedHeader)) return null;

  return { path, lines, reason: "maintained source" };
};
