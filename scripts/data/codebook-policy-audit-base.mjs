export const makeAddressGapPronunciationKey = (language, word) => {
  if (
    [
      "swahili",
      "filipino",
      "hausa",
      "somali",
      "lingala",
      "malagasy",
      "oromo",
      "chichewa",
      "bambara",
      "fula",
      "wolof",
      "kinyarwanda",
      "kirundi",
      "krio",
      "ewe",
      "fon",
      "sango",
      "moore",
      "kanuri",
      "quechua",
      "aymara",
      "guarani",
      "kongo",
      "zarma",
      "tamasheq",
      "songhay",
      "twi",
      "dagbani",
      "luganda",
      "acholi",
      "dinka",
      "nuer",
      "shona",
      "ndebele",
      "tok_pisin",
    ].includes(language)
  ) {
    return String(word)
      .normalize("NFKD")
      .replace(/\p{Mark}/gu, "")
      .toLowerCase()
      .replace(/c/g, "k")
      .replace(/q/g, "k")
      .replace(/ph/g, "f")
      .replace(/([a-z])\1+/g, "$1");
  }

  const normalized = String(word)
    .normalize("NFC")
    .replace(/[\u200c\u200d\s]/g, "");
  if (language === "urdu") {
    return normalized.replace(/[\u064b-\u065f\u0670]/g, "");
  }
  return normalized.replace(/(.)\1+/gu, "$1");
};
