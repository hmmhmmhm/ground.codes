const transliterate = (value, script) => {
  const map = transliterationMaps[script];
  let output = "";
  for (const char of foldLatin(value).toLowerCase()) {
    if (/\d/.test(char) || /\s/.test(char)) {
      output += char;
      continue;
    }
    output += map?.[char] ?? "";
  }
  return output.replace(/\s+/g, " ").trim();
};

